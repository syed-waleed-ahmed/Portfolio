// Regenerates src/assets/skill-icons.svg, the sprite behind the brand marks in
// the Skills section. Run it after editing `skillIcons` in src/data/skills.js:
//
//   cd frontend
//   npm i --no-save --ignore-scripts simple-icons@16.36.0 @lobehub/icons-static-svg@1.101.0
//   node scripts/gen-skill-icons.mjs
//
// The marks come from two open-source sets: Simple Icons (CC0-1.0), and Lobe
// Icons (MIT) for the AI vendors Simple Icons does not carry. Simple Icons
// wins when both have an id, so a mark never changes because the other set
// added one.
//
// The packages are installed on demand, like the ones scripts/gen-og-card.mjs
// needs at the repository root: together they hold some 4,500 files, and the
// site uses a few dozen paths from them. The sprite is committed, so a build
// never needs either package. Install both in one command, since a second
// `npm i --no-save` prunes what the first added.
//
// Each icon becomes a <symbol> holding only its paths, with no fill of its
// own, so the page colours it through `fill: currentColor`. An icon that is
// anything but plain paths stops the run: a gradient or a nested group would
// otherwise render as a black square nobody asked for.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { skillIcons } from "../src/data/skills.js";

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(frontend, "src/assets/skill-icons.svg");

// In lookup order.
const SETS = [
  { name: "simple-icons", licence: "CC0-1.0" },
  { name: "@lobehub/icons-static-svg", licence: "MIT" },
].map((set) => {
  const dir = path.join(frontend, "node_modules", set.name);
  if (!existsSync(dir)) {
    throw new Error(`${set.name} is not installed. Run the npm command at the top of this file first.`);
  }
  const { version } = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
  return { ...set, dir, version };
});

const PATH_ATTRIBUTES = new Set(["d", "fill-rule", "clip-rule"]);

const toSymbol = (id) => {
  const set = SETS.find(({ dir }) => existsSync(path.join(dir, "icons", `${id}.svg`)));
  if (!set) throw new Error(`No icon "${id}" in ${SETS.map(({ name }) => name).join(" or ")}.`);

  const source = readFileSync(path.join(set.dir, "icons", `${id}.svg`), "utf8");
  const root = source.match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  if (!root) throw new Error(`${id}: not a single <svg> element.`);
  const [, rootAttributes, body] = root;

  const viewBox = rootAttributes.match(/\bviewBox="([^"]+)"/)?.[1];
  if (viewBox !== "0 0 24 24") throw new Error(`${id}: unexpected viewBox "${viewBox}".`);
  // Lobe Icons set the fill rule once on the root, where the paths inherit it.
  const fillRule = rootAttributes.match(/\bfill-rule="([^"]+)"/)?.[1];

  const paths = [];
  const rest = body
    .replace(/<title>[^<]*<\/title>/, "")
    .replace(/<path\b([^>]*?)\s*(?:\/>|><\/path>)/g, (_, attributes) => {
      const kept = [...attributes.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, name, value]) => {
        if (!PATH_ATTRIBUTES.has(name)) throw new Error(`${id}: <path> carries "${name}", which the sprite would drop.`);
        return `${name}="${value}"`;
      });
      paths.push(`<path ${kept.join(" ")}/>`);
      return "";
    });
  if (rest.trim() || paths.length === 0) throw new Error(`${id}: holds more than plain paths: ${rest.trim().slice(0, 80)}`);

  const rule = fillRule ? ` fill-rule="${fillRule}"` : "";
  return { set, markup: `<symbol id="${id}" viewBox="${viewBox}"${rule}>${paths.join("")}</symbol>` };
};

const ids = [...new Set(Object.values(skillIcons))].sort();
const symbols = ids.map((id) => ({ id, ...toSymbol(id) }));

const credits = SETS.map(({ name, version, licence }) => `${name} ${version} (${licence})`).join(" and ");
const sprite = [
  '<svg xmlns="http://www.w3.org/2000/svg">',
  `<!-- Generated by scripts/gen-skill-icons.mjs from ${credits}. Do not edit by hand.`,
  "     The marks are trademarks of their owners, shown to name the tool beside them. -->",
  ...symbols.map(({ markup }) => markup),
  "</svg>",
  "",
].join("\n");

writeFileSync(OUTPUT, sprite);

for (const set of SETS) {
  const from = symbols.filter((symbol) => symbol.set === set).map(({ id }) => id);
  console.log(`${set.name} ${set.version}: ${from.length} (${from.join(", ")})`);
}
console.log(`wrote ${ids.length} symbols, ${(sprite.length / 1024).toFixed(1)} KB, to ${path.relative(frontend, OUTPUT)}`);
